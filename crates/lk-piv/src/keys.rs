//! Asymmetric slot keys: algorithms, PIN and touch policies, the persisted key record and
//! the private key operations behind GENERAL AUTHENTICATE.
//!
//! Sources:
//!
//! - Algorithm identifiers: SP 800-78-4 Table 6-2 (`06` RSA-1024, `07` RSA-2048, `11`
//!   ECC P-256, `14` ECC P-384) and the Yubico PIV extensions (`05` RSA-3072, `16`
//!   RSA-4096, `E0` Ed25519, `E1` X25519; firmware 5.7).
//! - Public key data objects: SP 800-73-4 Part 2 §3.3.2 Table 10 (`7F49` with `81`
//!   modulus and `82` exponent for RSA, `86` point for ECC); Yubico uses `86` for the 32-byte
//!   Ed25519 and X25519 public keys.
//! - Import data: Yubico PIV extensions, IMPORT ASYMMETRIC KEY (`01` P, `02` Q, `03` dP,
//!   `04` dQ, `05` qInv for RSA, `06` private scalar for ECC; `07` Ed25519 seed and `08`
//!   X25519 private key for the 5.7 algorithms).
//! - PIN policy `AA` (`00` default, `01` never, `02` once, `03` always) and touch policy
//!   `AB` (`00` default, `01` never, `02` always, `03` cached for 15 s): Yubico PIV
//!   extensions, "PIN and touch policy". The biometric match policies `04`/`05` exist only
//!   on YubiKey Bio and are rejected on the reference key.
//! - Per-slot default PIN policies (Yubico PIV documentation, "Certificate slots"): `9C`
//!   always, `9E` never, every other slot once. The default touch policy is never.
//!
//! RSA keys always use the public exponent 65537: keys generated by `lk_crypto` use it, and
//! Yubico's tools refuse to import any other exponent (the device derives the public key
//! it reports from that assumption). Imported CRT components must be consistent with it
//! (`bignum::crt_consistent`).

