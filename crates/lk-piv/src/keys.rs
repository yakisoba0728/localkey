/// The only RSA public exponent the model supports (65537).
pub(crate) const RSA_EXPONENT: [u8; 3] = [0x01, 0x00, 0x01];

/// Slot `9C`, Digital Signature (SP 800-73-4 Part 1 §3.1.3).
const SLOT_SIGNATURE: u8 = 0x9C;
/// Slot `9E`, Card Authentication (SP 800-73-4 Part 1 §3.1.4).
const SLOT_CARD_AUTH: u8 = 0x9E;
/// Slot `F9`, Yubico attestation.
const SLOT_ATTESTATION: u8 = 0xF9;

/// Public key template elements (SP 800-73-4 Part 2 Table 10).
pub(crate) const TAG_PUBLIC_KEY: u32 = 0x7F49;
const TAG_MODULUS: u32 = 0x81;
const TAG_EXPONENT: u32 = 0x82;
const TAG_POINT: u32 = 0x86;

/// IMPORT ASYMMETRIC KEY data tags (Yubico PIV extensions).
const TAG_RSA_P: u32 = 0x01;
const TAG_RSA_Q: u32 = 0x02;
const TAG_RSA_DP: u32 = 0x03;
const TAG_RSA_DQ: u32 = 0x04;
const TAG_RSA_QINV: u32 = 0x05;
const TAG_EC_SCALAR: u32 = 0x06;
const TAG_ED25519_SEED: u32 = 0x07;
const TAG_X25519_SECRET: u32 = 0x08;
/// PIN policy and touch policy tags (Yubico PIV extensions).
pub(crate) const TAG_PIN_POLICY: u32 = 0xAA;
pub(crate) const TAG_TOUCH_POLICY: u32 = 0xAB;

/// Asymmetric algorithms of firmware 5.7.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum KeyAlg {
    Rsa1024,
    Rsa2048,
    Rsa3072,
    Rsa4096,
    P256,
    P384,
    Ed25519,
    X25519,
}

impl KeyAlg {
    /// The algorithm for an identifier byte (SP 800-78-4 Table 6-2; Yubico extensions).
    pub(crate) fn from_byte(b: u8) -> Option<Self> {
        match b {
            0x06 => Some(Self::Rsa1024),
            0x07 => Some(Self::Rsa2048),
            0x05 => Some(Self::Rsa3072),
            0x16 => Some(Self::Rsa4096),
            0x11 => Some(Self::P256),
            0x14 => Some(Self::P384),
            0xE0 => Some(Self::Ed25519),
            0xE1 => Some(Self::X25519),
            _ => None,
        }
    }

    pub(crate) fn byte(self) -> u8 {
        match self {
            Self::Rsa1024 => 0x06,
            Self::Rsa2048 => 0x07,
            Self::Rsa3072 => 0x05,
            Self::Rsa4096 => 0x16,
            Self::P256 => 0x11,
            Self::P384 => 0x14,
            Self::Ed25519 => 0xE0,
            Self::X25519 => 0xE1,
        }
    }

    /// Modulus length in bits for RSA.
    pub(crate) fn rsa_bits(self) -> Option<usize> {
        match self {
            Self::Rsa1024 => Some(1024),
            Self::Rsa2048 => Some(2048),
            Self::Rsa3072 => Some(3072),
            Self::Rsa4096 => Some(4096),
            _ => None,
        }
    }

    /// The NIST curve for ECC.
    pub(crate) fn curve(self) -> Option<Curve> {
        match self {
            Self::P256 => Some(Curve::P256),
            Self::P384 => Some(Curve::P384),
            _ => None,
        }
    }

    /// Whether the attestation slot `F9` may hold a key of this algorithm: the profile's
    /// `attestation_key_algorithms` (ECC P-256, ECC P-384, RSA-2048, RSA-3072, RSA-4096;
    /// catalog "five supported generation algorithms and imported RSA/EC issuers").
    pub(crate) fn can_attest(self) -> bool {
        matches!(self, Self::P256 | Self::P384 | Self::Rsa2048 | Self::Rsa3072 | Self::Rsa4096)
    }
}

/// Where a key came from (GET METADATA tag `03`: `01` generated, `02` imported).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Origin {
    Generated,
    Imported,
}

impl Origin {
    pub(crate) fn byte(self) -> u8 {
        match self {
            Self::Generated => 0x01,
            Self::Imported => 0x02,
        }
    }

    fn from_byte(b: u8) -> Option<Self> {
        match b {
            0x01 => Some(Self::Generated),
            0x02 => Some(Self::Imported),
            _ => None,
        }
    }
}

/// PIN policy, resolved (never "default"): `01` never, `02` once per session, `03` before
/// every use.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum PinPolicy {
    Never,
    Once,
    Always,
}

impl PinPolicy {
    pub(crate) fn byte(self) -> u8 {
        match self {
            Self::Never => 0x01,
            Self::Once => 0x02,
            Self::Always => 0x03,
        }
    }

    /// The policy for the `AA` value `b` in `slot`; `00` is the slot default. Anything
    /// else, including the biometric `04`/`05`, is `6A80`.
    pub(crate) fn parse(b: u8, slot: u8) -> Result<Self, u16> {
        match b {
            0x00 => Ok(Self::slot_default(slot)),
            0x01 => Ok(Self::Never),
            0x02 => Ok(Self::Once),
            0x03 => Ok(Self::Always),
            _ => Err(sw::INCORRECT_DATA),
        }
    }

    /// Default PIN policy of a slot (Yubico "Certificate slots"; the attestation slot is
    /// never used with a PIN).
    pub(crate) fn slot_default(slot: u8) -> Self {
        match slot {
            SLOT_SIGNATURE => Self::Always,
            SLOT_CARD_AUTH | SLOT_ATTESTATION => Self::Never,
            _ => Self::Once,
        }
    }

    fn from_byte(b: u8) -> Option<Self> {
        match b {
            0x01 => Some(Self::Never),
            0x02 => Some(Self::Once),
            0x03 => Some(Self::Always),
            _ => None,
        }
    }
}

/// Touch policy, resolved: `01` never, `02` always, `03` cached for 15 seconds.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum TouchPolicy {
    Never,
    Always,
    Cached,
}

impl TouchPolicy {
    pub(crate) fn byte(self) -> u8 {
        match self {
            Self::Never => 0x01,
            Self::Always => 0x02,
            Self::Cached => 0x03,
        }
    }

    /// The policy for the `AB` value `b`; `00` is the default (never). Anything else is
    /// `6A80`.
    pub(crate) fn parse(b: u8) -> Result<Self, u16> {
        match b {
            0x00 | 0x01 => Ok(Self::Never),
            0x02 => Ok(Self::Always),
            0x03 => Ok(Self::Cached),
            _ => Err(sw::INCORRECT_DATA),
        }
    }

    fn from_byte(b: u8) -> Option<Self> {
        match b {
            0x01 => Some(Self::Never),
            0x02 => Some(Self::Always),
            0x03 => Some(Self::Cached),
            _ => None,
        }
    }
}

/// Private key material as persisted, wiped when dropped (`lk_crypto::SecretBytes`;
/// `docs/DESIGN.md` §8).
#[derive(Clone, PartialEq, Eq)]
pub(crate) enum Private {
    /// RSA primes, big-endian; the exponent is [`RSA_EXPONENT`].
    Rsa { p: SecretBytes, q: SecretBytes },
    /// ECC private scalar (field length), Ed25519 seed or X25519 private key (32 bytes).
    Bytes(SecretBytes),
}

/// A key held in a slot.
#[derive(Clone, PartialEq, Eq)]
pub(crate) struct SlotKey {
    pub(crate) alg: KeyAlg,
    pub(crate) pin: PinPolicy,
    pub(crate) touch: TouchPolicy,
    pub(crate) origin: Origin,
    pub(crate) private: Private,
    /// RSA modulus, uncompressed ECC point, or the 32-byte Ed25519/X25519 public key.
    pub(crate) public: Vec<u8>,
}

impl fmt::Debug for SlotKey {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        // Private material is never shown.
        f.debug_struct("SlotKey")
            .field("alg", &self.alg)
            .field("pin", &self.pin)
            .field("touch", &self.touch)
            .field("origin", &self.origin)
            .finish_non_exhaustive()
    }
}

/// What GENERAL AUTHENTICATE asks of a slot key (SP 800-73-4 Part 2 Table 7).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Operation {
    /// Tag `81`: RSA private operation (sign or decrypt), ECDSA over a digest, or Ed25519
    /// over a message.
    Challenge,
    /// Tag `85`: key agreement with the peer's public key (ECDH, X25519).
    Exponentiation,
}

// Persisted record tags inside a slot entry (`state` tag `71`, element `02`).
const R_ALG: u32 = 0x01;
const R_PIN: u32 = 0x02;
const R_TOUCH: u32 = 0x03;
const R_ORIGIN: u32 = 0x04;
const R_SECRET: u32 = 0x05;
const R_P: u32 = 0x06;
const R_Q: u32 = 0x07;
const R_PUBLIC: u32 = 0x08;

/// Big-endian bytes without leading zeros.
pub(crate) fn trimmed(bytes: &[u8]) -> &[u8] {
    let start = bytes.iter().position(|&b| b != 0).unwrap_or(bytes.len());
    bytes.get(start..).unwrap_or_default()
}

fn crypto_failure<E>(_: E) -> u16 {
    sw::UNKNOWN
}

impl SlotKey {
    /// Generate a key on the device (GENERATE ASYMMETRIC KEY PAIR).
    pub(crate) fn generate(
        alg: KeyAlg,
        pin: PinPolicy,
        touch: TouchPolicy,
        entropy: &mut dyn Entropy,
    ) -> Result<Self, u16> {
        let (private, public) = if let Some(bits) = alg.rsa_bits() {
            let key = RsaPrivateKey::generate(bits, entropy).map_err(crypto_failure)?;
            if key.public_exponent() != RSA_EXPONENT || key.size() * 8 != bits {
                return Err(sw::UNKNOWN);
            }
            let primes = key.primes();
            let private = Private::Rsa { p: SecretBytes::from_slice(&primes.0), q: SecretBytes::from_slice(&primes.1) };
            (private, key.modulus())
        } else if let Some(curve) = alg.curve() {
            let key = EcPrivateKey::generate(curve, entropy);
            (Private::Bytes(SecretBytes::from_slice(key.scalar())), key.public_uncompressed())
        } else if alg == KeyAlg::Ed25519 {
            let key = Ed25519Key::generate(entropy);
            (Private::Bytes(SecretBytes::from_slice(key.seed())), key.public().to_vec())
        } else {
            let key = X25519Key::generate(entropy);
            (Private::Bytes(SecretBytes::from_slice(key.secret())), key.public().to_vec())
        };
        Ok(Self { alg, pin, touch, origin: Origin::Generated, private, public })
    }

    /// Build a key from IMPORT ASYMMETRIC KEY elements. `items` holds the key elements
    /// only (policy tags already removed) and must contain exactly the elements of the
    /// algorithm, each once (`6A80` otherwise).
    ///
    /// - RSA: P and Q must yield a modulus of exactly the algorithm's length with the
    ///   exponent 65537, and dP, dQ and qInv must match them (RFC 8017 §3.2).
    /// - ECC: the scalar must have the field length and lie in `1..n` (SEC 1 §3.2.1).
    /// - Ed25519 seed (RFC 8032 §5.1.5) and X25519 private key (RFC 7748 §5): 32 bytes.
    pub(crate) fn import(alg: KeyAlg, pin: PinPolicy, touch: TouchPolicy, items: &[Tlv<'_>]) -> Result<Self, u16> {
        let expected: &[u32] = if alg.rsa_bits().is_some() {
            &[TAG_RSA_P, TAG_RSA_Q, TAG_RSA_DP, TAG_RSA_DQ, TAG_RSA_QINV]
        } else if alg.curve().is_some() {
            &[TAG_EC_SCALAR]
        } else if alg == KeyAlg::Ed25519 {
            &[TAG_ED25519_SEED]
        } else {
            &[TAG_X25519_SECRET]
        };
        if items.len() != expected.len() || !expected.iter().all(|t| items.iter().filter(|i| i.tag == *t).count() == 1)
        {
            return Err(sw::INCORRECT_DATA);
        }
        let get = |tag: u32| tlv::find(items, tag).map(|t| t.value).ok_or(sw::INCORRECT_DATA);
        let (private, public) = if let Some(bits) = alg.rsa_bits() {
            let (p, q) = (trimmed(get(TAG_RSA_P)?), trimmed(get(TAG_RSA_Q)?));
            let half = bits / 16;
            if p.len() > half || q.len() > half {
                return Err(sw::INCORRECT_DATA);
            }
            let key = RsaPrivateKey::from_primes(p, q, &RSA_EXPONENT).map_err(|_| sw::INCORRECT_DATA)?;
            if key.size() * 8 != bits {
                return Err(sw::INCORRECT_DATA);
            }
            if !bignum::crt_consistent(p, q, &RSA_EXPONENT, get(TAG_RSA_DP)?, get(TAG_RSA_DQ)?, get(TAG_RSA_QINV)?) {
                return Err(sw::INCORRECT_DATA);
            }
            (Private::Rsa { p: SecretBytes::from_slice(p), q: SecretBytes::from_slice(q) }, key.modulus())
        } else if let Some(curve) = alg.curve() {
            let key = EcPrivateKey::from_scalar(curve, get(TAG_EC_SCALAR)?).map_err(|_| sw::INCORRECT_DATA)?;
            (Private::Bytes(SecretBytes::from_slice(key.scalar())), key.public_uncompressed())
        } else if alg == KeyAlg::Ed25519 {
            let key = Ed25519Key::from_seed(get(TAG_ED25519_SEED)?).map_err(|_| sw::INCORRECT_DATA)?;
            (Private::Bytes(SecretBytes::from_slice(key.seed())), key.public().to_vec())
        } else {
            let key = X25519Key::from_bytes(get(TAG_X25519_SECRET)?).map_err(|_| sw::INCORRECT_DATA)?;
            (Private::Bytes(SecretBytes::from_slice(key.secret())), key.public().to_vec())
        };
        Ok(Self { alg, pin, touch, origin: Origin::Imported, private, public })
    }

    /// The public key data elements without the `7F49` wrapper: `81 n 82 e` for RSA, `86
    /// key` otherwise (SP 800-73-4 Part 2 Table 10). GET METADATA tag `04` carries the
    /// same elements.
    pub(crate) fn public_elements(&self) -> Vec<u8> {
        if self.alg.rsa_bits().is_some() {
            let mut out = tlv::encode(TAG_MODULUS, &self.public);
            tlv::encode_into(&mut out, TAG_EXPONENT, &RSA_EXPONENT);
            out
        } else {
            tlv::encode(TAG_POINT, &self.public)
        }
    }

    /// The public key for an X.509 SubjectPublicKeyInfo (RFC 5280 §4.1.2.7).
    pub(crate) fn x509_public(&self) -> PublicKey {
        match self.alg {
            KeyAlg::P256 => PublicKey::EcP256(self.public.clone()),
            KeyAlg::P384 => PublicKey::EcP384(self.public.clone()),
            KeyAlg::Ed25519 => PublicKey::Ed25519(self.public.clone()),
            KeyAlg::X25519 => PublicKey::X25519(self.public.clone()),
            _ => PublicKey::Rsa { modulus: self.public.clone(), exponent: RSA_EXPONENT.to_vec() },
        }
    }

    pub(crate) fn rsa_key(&self) -> Result<RsaPrivateKey, u16> {
        match &self.private {
            Private::Rsa { p, q } => RsaPrivateKey::from_primes(p, q, &RSA_EXPONENT).map_err(crypto_failure),
            Private::Bytes(_) => Err(sw::UNKNOWN),
        }
    }

    pub(crate) fn ec_key(&self) -> Result<EcPrivateKey, u16> {
        match (&self.private, self.alg.curve()) {
            (Private::Bytes(scalar), Some(curve)) => EcPrivateKey::from_scalar(curve, scalar).map_err(crypto_failure),
            _ => Err(sw::UNKNOWN),
        }
    }

    fn secret_bytes(&self) -> Result<&[u8], u16> {
        match &self.private {
            Private::Bytes(bytes) => Ok(bytes.as_slice()),
            Private::Rsa { .. } => Err(sw::UNKNOWN),
        }
    }

    /// Check a GENERAL AUTHENTICATE request before any PIN, touch or computation, so a
    /// malformed request is `6A80` without consuming anything:
    ///
    /// - RSA, `81`: exactly the modulus length and numerically below the modulus (RFC 8017
    ///   §5.1.2 step 1, §5.2.1 step 1).
    /// - ECC, `81`: a digest of 1 to field-length bytes; Yubico documents that the digest
    ///   must not be longer than the key ("256 bits or shorter for P-256").
    /// - ECC, `85`: an uncompressed point on the curve (SEC 1 §2.3.4; the documented
    ///   `04 || X || Y` form).
    /// - Ed25519, `81`: any message (RFC 8032 §5.1.6).
    /// - X25519, `85`: a 32-byte public key (RFC 7748 §5) that gives a non-zero shared
    ///   secret. RFC 7748 §6.1 lets a party "check ... whether K is the all-zero value and
    ///   abort if so"; a low-order peer key gives the all-zero value for every private
    ///   key, so it is a property of the request and is refused here, before the PIN
    ///   policy or a touch, like any other malformed request (crate documentation: a
    ///   rejected request keeps the PIN-always authorization).
    /// - Any other combination (RSA or Ed25519 with `85`, X25519 with `81`) is `6A80`.
    ///
    /// Every request that passes is one [`compute`](Self::compute) completes, so no
    /// authorization or touch is spent on a request that then fails.
    pub(crate) fn check_request(&self, op: Operation, input: &[u8]) -> Result<(), u16> {
        let ok = match (self.alg, op) {
            (_, Operation::Challenge) if self.alg.rsa_bits().is_some() => {
                input.len() == self.public.len() && input.cmp(self.public.as_slice()) == Ordering::Less
            }
            (KeyAlg::P256 | KeyAlg::P384, Operation::Challenge) => {
                let len = self.alg.curve().map_or(0, Curve::field_len);
                !input.is_empty() && input.len() <= len
            }
            (KeyAlg::P256, Operation::Exponentiation) => ec_public_is_valid(Curve::P256, input),
            (KeyAlg::P384, Operation::Exponentiation) => ec_public_is_valid(Curve::P384, input),
            (KeyAlg::Ed25519, Operation::Challenge) => true,
            (KeyAlg::X25519, Operation::Exponentiation) => self.x25519_contributory(input),
            _ => false,
        };
        if ok { Ok(()) } else { Err(sw::INCORRECT_DATA) }
    }

    /// Whether X25519 with `peer` (32 bytes) gives a non-zero shared secret (RFC 7748
    /// §6.1). The secret is computed and dropped at once (`X25519Key::dh` zeroizes it).
    fn x25519_contributory(&self, peer: &[u8]) -> bool {
        peer.len() == 32
            && self
                .secret_bytes()
                .ok()
                .and_then(|secret| X25519Key::from_bytes(secret).ok())
                .is_some_and(|key| key.dh(peer).is_ok())
    }

    /// Perform a request that passed [`check_request`](Self::check_request):
    ///
    /// - RSA: the raw private operation RSADP/RSASP1 (RFC 8017 §5.1.2, §5.2.1); padding is
    ///   the host's job (SP 800-73-4 Part 2 §3.2.4).
    /// - ECDSA (FIPS 186-5 §6.4.1) over the digest, left-padded with zeros to the field
    ///   length (the same integer), with a hedged nonce (`docs/CONTRACTS.md` "Phase 0 as
    ///   implemented"); the answer is the DER signature (SP 800-73-4 Part 2 Appendix A.4).
    /// - Ed25519 (RFC 8032 §5.1.6): the 64-byte signature.
    /// - ECDH (SP 800-56A §5.7.1.2): the X coordinate; X25519 (RFC 7748 §6.1): the shared
    ///   secret. A peer key that gives the all-zero X25519 secret is `6A80`.
    pub(crate) fn compute(&self, op: Operation, input: &[u8], entropy: &mut dyn Entropy) -> Result<Vec<u8>, u16> {
        match (self.alg, op) {
            (KeyAlg::P256 | KeyAlg::P384, Operation::Challenge) => {
                let key = self.ec_key()?;
                let len = key.curve().field_len();
                let mut digest = vec![0u8; len.saturating_sub(input.len())];
                digest.extend_from_slice(input);
                let signature = key.sign_prehash_hedged(&digest, entropy).map_err(|_| sw::INCORRECT_DATA)?;
                Ok(signature.to_der())
            }
            (KeyAlg::P256 | KeyAlg::P384, Operation::Exponentiation) => {
                let shared = self.ec_key()?.ecdh(input).map_err(|_| sw::INCORRECT_DATA)?;
                Ok(shared.to_vec())
            }
            (KeyAlg::Ed25519, Operation::Challenge) => {
                let key = Ed25519Key::from_seed(self.secret_bytes()?).map_err(crypto_failure)?;
                Ok(key.sign(input).to_vec())
            }
            (KeyAlg::X25519, Operation::Exponentiation) => {
                let key = X25519Key::from_bytes(self.secret_bytes()?).map_err(crypto_failure)?;
                let shared = key.dh(input).map_err(|_| sw::INCORRECT_DATA)?;
                Ok(shared.to_vec())
            }
            (_, Operation::Challenge) if self.alg.rsa_bits().is_some() => {
                self.rsa_key()?.raw_private(input, entropy).map_err(|_| sw::INCORRECT_DATA)
            }
            _ => Err(sw::INCORRECT_DATA),
        }
    }

    /// Serialize for the persisted slot entry (BER-TLV, ISO/IEC 7816-4 §5.2.2). The
    /// result holds the private key; the caller wraps it in `SecretBytes`. The buffer is
    /// sized up front ([`encoded_len_bound`](Self::encoded_len_bound)) so it never
    /// reallocates and leaves no unwiped copies.
    pub(crate) fn encode(&self) -> Vec<u8> {
        let mut out = Vec::with_capacity(self.encoded_len_bound());
        tlv::encode_into(&mut out, R_ALG, &[self.alg.byte()]);
        tlv::encode_into(&mut out, R_PIN, &[self.pin.byte()]);
        tlv::encode_into(&mut out, R_TOUCH, &[self.touch.byte()]);
        tlv::encode_into(&mut out, R_ORIGIN, &[self.origin.byte()]);
        match &self.private {
            Private::Rsa { p, q } => {
                tlv::encode_into(&mut out, R_P, p);
                tlv::encode_into(&mut out, R_Q, q);
            }
            Private::Bytes(bytes) => tlv::encode_into(&mut out, R_SECRET, bytes),
        }
        tlv::encode_into(&mut out, R_PUBLIC, &self.public);
        out
    }

    /// An upper bound on the length of [`encode`](Self::encode)'s result.
    pub(crate) fn encoded_len_bound(&self) -> usize {
        let private = match &self.private {
            Private::Rsa { p, q } => 2 * TLV_OVERHEAD + p.len() + q.len(),
            Private::Bytes(bytes) => TLV_OVERHEAD + bytes.len(),
        };
        4 * (TLV_OVERHEAD + 1) + private + TLV_OVERHEAD + self.public.len()
    }

    /// Parse a persisted slot entry. Only lengths are checked (the material was validated
    /// when it was created); unknown elements are skipped (`docs/CONTRACTS.md`).
    pub(crate) fn decode(bytes: &[u8]) -> Option<Self> {
        let items = tlv::parse_all(bytes).ok()?;
        let one = |tag: u32| match tlv::find(&items, tag)?.value {
            [b] => Some(*b),
            _ => None,
        };
        let value = |tag: u32| tlv::find(&items, tag).map(|t| t.value);
        let alg = KeyAlg::from_byte(one(R_ALG)?)?;
        let pin = PinPolicy::from_byte(one(R_PIN)?)?;
        let touch = TouchPolicy::from_byte(one(R_TOUCH)?)?;
        let origin = Origin::from_byte(one(R_ORIGIN)?)?;
        let public = value(R_PUBLIC)?.to_vec();
        let private = if let Some(bits) = alg.rsa_bits() {
            let (p, q) = (value(R_P)?, value(R_Q)?);
            let half = bits / 16;
            let sizes_ok = (1..=half).contains(&p.len()) && (1..=half).contains(&q.len());
            if !sizes_ok || public.len() != bits / 8 {
                return None;
            }
            Private::Rsa { p: SecretBytes::from_slice(p), q: SecretBytes::from_slice(q) }
        } else {
            let secret = value(R_SECRET)?;
            let (secret_len, public_len) = match alg.curve() {
                Some(curve) => (curve.field_len(), curve.point_len()),
                None => (32, 32),
            };
            if secret.len() != secret_len || public.len() != public_len {
                return None;
            }
            Private::Bytes(SecretBytes::from_slice(secret))
        };
        Some(Self { alg, pin, touch, origin, private, public })
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;
    use lk_core::Entropy;

    struct Counter(u8);

    impl Entropy for Counter {
        fn fill(&mut self, out: &mut [u8]) {
            for b in out {
                self.0 = self.0.wrapping_mul(29).wrapping_add(7);
                *b = self.0;
            }
        }
    }

    #[test]
    fn algorithm_bytes_round_trip() {
        // SP 800-78-4 Table 6-2 and the Yubico 5.7 identifiers.
        for b in [0x06, 0x07, 0x05, 0x16, 0x11, 0x14, 0xE0, 0xE1] {
            assert_eq!(KeyAlg::from_byte(b).unwrap().byte(), b);
        }
        for b in [0x00, 0x03, 0x08, 0x0A, 0x0C, 0x12, 0x15, 0xE2, 0xFF] {
            assert_eq!(KeyAlg::from_byte(b), None, "{b:02X}");
        }
    }

    #[test]
    fn policy_parsing_and_slot_defaults() {
        // Yubico "PIN and touch policy" values; "Certificate slots" defaults.
        assert_eq!(PinPolicy::parse(0, 0x9A), Ok(PinPolicy::Once));
        assert_eq!(PinPolicy::parse(0, 0x9C), Ok(PinPolicy::Always));
        assert_eq!(PinPolicy::parse(0, 0x9D), Ok(PinPolicy::Once));
        assert_eq!(PinPolicy::parse(0, 0x9E), Ok(PinPolicy::Never));
        assert_eq!(PinPolicy::parse(0, 0x82), Ok(PinPolicy::Once));
        assert_eq!(PinPolicy::parse(3, 0x9E), Ok(PinPolicy::Always));
        assert_eq!(PinPolicy::parse(4, 0x9A), Err(sw::INCORRECT_DATA), "match once needs biometrics");
        assert_eq!(PinPolicy::parse(5, 0x9A), Err(sw::INCORRECT_DATA), "match always needs biometrics");
        assert_eq!(TouchPolicy::parse(0), Ok(TouchPolicy::Never));
        assert_eq!(TouchPolicy::parse(3), Ok(TouchPolicy::Cached));
        assert_eq!(TouchPolicy::parse(4), Err(sw::INCORRECT_DATA));
    }

    #[test]
    fn slot_records_round_trip() {
        for alg in [KeyAlg::P256, KeyAlg::P384, KeyAlg::Ed25519, KeyAlg::X25519, KeyAlg::Rsa1024] {
            let key = SlotKey::generate(alg, PinPolicy::Always, TouchPolicy::Cached, &mut Counter(1)).unwrap();
            let decoded = SlotKey::decode(&key.encode()).unwrap();
            assert!(decoded == key, "{alg:?}");
        }
    }

    #[test]
    fn slot_record_lengths_are_checked() {
        let key = SlotKey::generate(KeyAlg::P256, PinPolicy::Once, TouchPolicy::Never, &mut Counter(2)).unwrap();
        let mut bad = key.clone();
        bad.public.pop();
        assert!(SlotKey::decode(&bad.encode()).is_none());
        let mut bad = key;
        bad.private = Private::Bytes(vec![1; 31].into());
        assert!(SlotKey::decode(&bad.encode()).is_none());
        assert!(SlotKey::decode(&[0x01, 0x01, 0x11]).is_none(), "missing fields");
    }
}
