#!/usr/bin/env python3
"""Enforce the dependency policy of docs/DESIGN.md §8 and write THIRD_PARTY.md.

Checks:
1. Only `lk-crypto` may depend directly on third-party crates.
2. Every third-party crate in the build graph has a license expression that can be
   satisfied with the allowlist below.

`python3 tools/license_check.py` checks; add `--write` to regenerate THIRD_PARTY.md.
Standard library only.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
allowed = {"MIT", "Apache-2.0", "BSD-3-Clause", "BSD-2-Clause", "BSD-1-Clause", "ISC",
           "Zlib", "Unicode-3.0", "0BSD"}
third_party_gateways = {"lk-crypto"}


def satisfiable(expression: str) -> bool:
    """True if an SPDX-like expression can be met using only allowed licenses."""
    tokens = re.findall(r"\(|\)|[A-Za-z0-9.+-]+", expression.replace("/", " OR "))
    position = 0

    def parse_or() -> bool:
        nonlocal position
        value = parse_and()
        while position < len(tokens) and tokens[position] == "OR":
            position += 1
            value = parse_and() or value
        return value

    def parse_and() -> bool:
        nonlocal position
        value = parse_atom()
        while position < len(tokens) and tokens[position] == "AND":
            position += 1
            value = parse_atom() and value
        return value

    def parse_atom() -> bool:
        nonlocal position
        token = tokens[position]
        position += 1
        if token == "(":
            value = parse_or()
            position += 1  # ")"
            return value
        return token in allowed

    result = parse_or()
    return result and position == len(tokens)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true", help="regenerate THIRD_PARTY.md")
    args = parser.parse_args()
    metadata = json.loads(subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked"],
        cwd=root, check=True, capture_output=True, text=True).stdout)
    packages = {p["id"]: p for p in metadata["packages"]}
    nodes = {n["id"]: n for n in metadata["resolve"]["nodes"]}
    workspace = {p["id"] for p in metadata["packages"] if p["source"] is None}
    problems = []

    for member in workspace:
        name = packages[member]["name"]
        for dep in nodes[member]["deps"]:
            normal = any(kind["kind"] is None for kind in dep["dep_kinds"])
            if normal and dep["pkg"] not in workspace and name not in third_party_gateways:
                problems.append(f"{name} depends directly on {packages[dep['pkg']]['name']}")

    def is_proc_macro(package_id: str) -> bool:
        return any("proc-macro" in target["kind"] for target in packages[package_id]["targets"])

    # Linked: reachable through normal edges without passing through a proc-macro crate.
    linked, build_only, stack = set(), set(), [(member, False) for member in workspace]
    visited = set()
    while stack:
        current, host_only = stack.pop()
        if (current, host_only) in visited:
            continue
        visited.add((current, host_only))
        for dep in nodes[current]["deps"]:
            kinds = {kind["kind"] for kind in dep["dep_kinds"]}
            if not kinds & {None, "build"}:
                continue  # dev-dependencies are not part of the shipped graph
            target = dep["pkg"]
            only_host = host_only or "build" in kinds and None not in kinds or is_proc_macro(target)
            if target not in workspace:
                (build_only if only_host else linked).add(target)
            stack.append((target, only_host))
    build_only -= linked

    rows = []
    for package_id in sorted(linked | build_only, key=lambda i: (packages[i]["name"], packages[i]["version"])):
        package = packages[package_id]
        license_text = package.get("license") or "(none)"
        if not satisfiable(license_text):
            problems.append(f"{package['name']} {package['version']}: license {license_text!r} not allowed")
        rows.append((package["name"], package["version"], license_text,
                     "linked" if package_id in linked else "build-time only",
                     package.get("repository") or ""))

    if args.write:
        lines = [
            "# Third-party components",
            "",
            "Generated by `python3 tools/license_check.py --write` from `Cargo.lock`. Every crate below",
            "is pulled in through `lk-crypto` (docs/DESIGN.md §8). \"linked\" crates end up in engine",
            "binaries; \"build-time only\" crates run in the compiler (procedural macros and build",
            "scripts) and are not shipped. Distributing binaries requires including the license",
            "texts of the linked crates, which are permissive (MIT, Apache-2.0, BSD).",
            "",
            f"Linked: {sum(r[3] == 'linked' for r in rows)}. Build-time only: {sum(r[3] != 'linked' for r in rows)}.",
            "",
            "| Crate | Version | License | Use | Source |",
            "| --- | --- | --- | --- | --- |",
        ]
        lines += [f"| {n} | {v} | {l} | {u} | {s} |" for n, v, l, u, s in rows]
        (root / "THIRD_PARTY.md").write_text("\n".join(lines) + "\n")

    summary = {"third_party_crates": len(rows),
               "linked": sum(r[3] == "linked" for r in rows),
               "build_time_only": sum(r[3] != "linked" for r in rows),
               "problems": problems}
    print(json.dumps(summary, indent=2))
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    main()
